main:
    la   s0, x
    li   s1, 1024

    # --------------------------------
    # BIT REVERSAL
    # --------------------------------

    li   t0, 1
    li   t1, 0

bitrev_i:
    bge  t0, s1, bitrev_done

    li   t2, 512

bitrev_carry:
    and  t5, t1, t2
    beq  t5, zero, bitrev_toggle

    xor  t1, t1, t2
    srli t2, t2, 1
    j    bitrev_carry

bitrev_toggle:
    xor  t1, t1, t2

    bge  t0, t1, bitrev_next

    slli t3, t0, 3
    add  t3, s0, t3

    slli t4, t1, 3
    add  t4, s0, t4

    vld  v0, 0(t3)
    vld  v1, 0(t4)

    vsd  v1, 0(t3)
    vsd  v0, 0(t4)

bitrev_next:
    addi t0, t0, 1
    j    bitrev_i


    # --------------------------------
    # FFT INITIALIZATION
    # --------------------------------

bitrev_done:
    li   t0, 2

    la   s2, wlen_table
    la   a5, one_zero
    la   a6, current_w
    la   a7, fft_tmp

    la   s3, vmul_same_tmp
    la   s4, vmul_cross_tmp
    la   s5, twiddle_tmp
    la   s6, w_batch


    # --------------------------------
    # FFT STAGE LOOP
    # --------------------------------

stage_loop:
    blt  s1, t0, fft_done

    li   t1, 0

block_loop:
    bge  t1, s1, stage_done

    # Reset W = 1 + 0i at the beginning
    # of every block.

    flw  ft4, 0(a5)
    flw  ft5, 4(a5)

    fsw  ft4, 0(a6)
    fsw  ft5, 4(a6)

    li   t2, 0
    srli t3, t0, 1

    # If fewer than 8 butterflies are
    # available, use the scalar path.

    li   t4, 8
    blt  t3, t4, small_butterfly_loop


    # --------------------------------
    # GENERATE 8 TWIDDLE FACTORS
    # USING VMUL + VSWAP
    # --------------------------------

unroll_loop:

    bge  t2, t3, butterfly_done

    la   a2, w_batch

    # Wlen vector
    vld  v25, 0(s2)

    li   t4, 8

w_batch_loop:

    # Save current W in the batch array.

    vld  v24, 0(a6)
    vsd  v24, 0(a2)

    addi a2, a2, 8

    # W = W * Wlen

    vmul  v26, v24, v25

    vswap v27, v24

    vmul  v28, v27, v25

    vsd   v26, 0(s3)
    vsd   v28, 0(s4)

    # Extract real and imaginary parts.

    flw  ft6, 0(s3)
    flw  ft7, 4(s3)

    fsub.s ft8, ft6, ft7

    flw  ft6, 0(s4)
    flw  ft7, 4(s4)

    fadd.s ft9, ft6, ft7

    # Save updated W.

    fsw  ft8, 0(a6)
    fsw  ft9, 4(a6)

    addi t4, t4, -1
    beq  t4, zero, w_batch_done
    j    w_batch_loop

    w_batch_done:


    # --------------------------------
    # LOAD 8 A VALUES
    # --------------------------------

    add  a0, t1, t2
    slli a0, a0, 3
    add  a0, s0, a0

    add  a1, t1, t2
    add  a1, a1, t3
    slli a1, a1, 3
    add  a1, s0, a1

    vld  v0,  0(a0)
    vld  v1,  8(a0)
    vld  v2, 16(a0)
    vld  v3, 24(a0)
    vld  v4, 32(a0)
    vld  v5, 40(a0)
    vld  v6, 48(a0)
    vld  v7, 56(a0)


    # --------------------------------
    # LOAD 8 B VALUES
    # --------------------------------

    vld  v8,  0(a1)
    vld  v9,  8(a1)
    vld  v10, 16(a1)
    vld  v11, 24(a1)
    vld  v12, 32(a1)
    vld  v13, 40(a1)
    vld  v14, 48(a1)
    vld  v15, 56(a1)


    # --------------------------------
    # LOAD 8 TWIDDLE FACTORS
    # --------------------------------

    vld  v16,  0(s6)
    vld  v17,  8(s6)
    vld  v18, 16(s6)
    vld  v19, 24(s6)
    vld  v20, 32(s6)
    vld  v21, 40(s6)
    vld  v22, 48(s6)
    vld  v23, 56(s6)


    # --------------------------------
    # SAME-LANE MULTIPLICATIONS
    # P = B * W
    # --------------------------------

    vmul v24, v8,  v16
    vmul v25, v9,  v17
    vmul v26, v10, v18
    vmul v27, v11, v19
    vmul v28, v12, v20
    vmul v29, v13, v21
    vmul v30, v14, v22
    vmul v31, v15, v23

    # Store same-lane products.

    vsd v24,  0(s3)
    vsd v25,  8(s3)
    vsd v26, 16(s3)
    vsd v27, 24(s3)
    vsd v28, 32(s3)
    vsd v29, 40(s3)
    vsd v30, 48(s3)
    vsd v31, 56(s3)


    # --------------------------------
    # CROSS-LANE MULTIPLICATIONS
    # Q = SWAP(B) * W
    # --------------------------------

    vswap v24, v8
    vmul  v24, v24, v16
    vsd   v24, 0(s4)

    vswap v24, v9
    vmul  v24, v24, v17
    vsd   v24, 8(s4)

    vswap v24, v10
    vmul  v24, v24, v18
    vsd   v24, 16(s4)

    vswap v24, v11
    vmul  v24, v24, v19
    vsd   v24, 24(s4)

    vswap v24, v12
    vmul  v24, v24, v20
    vsd   v24, 32(s4)

    vswap v24, v13
    vmul  v24, v24, v21
    vsd   v24, 40(s4)

    vswap v24, v14
    vmul  v24, v24, v22
    vsd   v24, 48(s4)

    vswap v24, v15
    vmul  v24, v24, v23
    vsd   v24, 56(s4)


    # --------------------------------
    # COMBINE SAME AND CROSS PRODUCTS
    # T.real = P.real - P.imag
    # T.imag = Q.real + Q.imag
    # --------------------------------

    # Butterfly 0

    flw  ft6, 0(s3)
    flw  ft7, 4(s3)
    fsub.s ft8, ft6, ft7

    flw  ft6, 0(s4)
    flw  ft7, 4(s4)
    fadd.s ft9, ft6, ft7

    fsw  ft8, 0(s5)
    fsw  ft9, 4(s5)

    # Butterfly 1

    flw  ft6, 8(s3)
    flw  ft7, 12(s3)
    fsub.s ft8, ft6, ft7

    flw  ft6, 8(s4)
    flw  ft7, 12(s4)
    fadd.s ft9, ft6, ft7

    fsw  ft8, 8(s5)
    fsw  ft9, 12(s5)

    # Butterfly 2

    flw  ft6, 16(s3)
    flw  ft7, 20(s3)
    fsub.s ft8, ft6, ft7

    flw  ft6, 16(s4)
    flw  ft7, 20(s4)
    fadd.s ft9, ft6, ft7

    fsw  ft8, 16(s5)
    fsw  ft9, 20(s5)

    # Butterfly 3

    flw  ft6, 24(s3)
    flw  ft7, 28(s3)
    fsub.s ft8, ft6, ft7

    flw  ft6, 24(s4)
    flw  ft7, 28(s4)
    fadd.s ft9, ft6, ft7

    fsw  ft8, 24(s5)
    fsw  ft9, 28(s5)

    # Butterfly 4

    flw  ft6, 32(s3)
    flw  ft7, 36(s3)
    fsub.s ft8, ft6, ft7

    flw  ft6, 32(s4)
    flw  ft7, 36(s4)
    fadd.s ft9, ft6, ft7

    fsw  ft8, 32(s5)
    fsw  ft9, 36(s5)

    # Butterfly 5

    flw  ft6, 40(s3)
    flw  ft7, 44(s3)
    fsub.s ft8, ft6, ft7

    flw  ft6, 40(s4)
    flw  ft7, 44(s4)
    fadd.s ft9, ft6, ft7

    fsw  ft8, 40(s5)
    fsw  ft9, 44(s5)

    # Butterfly 6

    flw  ft6, 48(s3)
    flw  ft7, 52(s3)
    fsub.s ft8, ft6, ft7

    flw  ft6, 48(s4)
    flw  ft7, 52(s4)
    fadd.s ft9, ft6, ft7

    fsw  ft8, 48(s5)
    fsw  ft9, 52(s5)

    # Butterfly 7

    flw  ft6, 56(s3)
    flw  ft7, 60(s3)
    fsub.s ft8, ft6, ft7

    flw  ft6, 56(s4)
    flw  ft7, 60(s4)
    fadd.s ft9, ft6, ft7

    fsw  ft8, 56(s5)
    fsw  ft9, 60(s5)


    # --------------------------------
    # LOAD 8 COMPLEX PRODUCTS
    # INTO B REGISTERS
    # --------------------------------

    vld  v8,  0(s5)
    vld  v9,  8(s5)
    vld  v10, 16(s5)
    vld  v11, 24(s5)
    vld  v12, 32(s5)
    vld  v13, 40(s5)
    vld  v14, 48(s5)
    vld  v15, 56(s5)


    # --------------------------------
    # EIGHT BUTTERFLIES
    # A + T AND A - T
    # --------------------------------

    vadd v24, v0, v8
    vsd  v24, 0(a0)
    vsub v24, v0, v8
    vsd  v24, 0(a1)

    vadd v24, v1, v9
    vsd  v24, 8(a0)
    vsub v24, v1, v9
    vsd  v24, 8(a1)

    vadd v24, v2, v10
    vsd  v24, 16(a0)
    vsub v24, v2, v10
    vsd  v24, 16(a1)

    vadd v24, v3, v11
    vsd  v24, 24(a0)
    vsub v24, v3, v11
    vsd  v24, 24(a1)

    vadd v24, v4, v12
    vsd  v24, 32(a0)
    vsub v24, v4, v12
    vsd  v24, 32(a1)

    vadd v24, v5, v13
    vsd  v24, 40(a0)
    vsub v24, v5, v13
    vsd  v24, 40(a1)

    vadd v24, v6, v14
    vsd  v24, 48(a0)
    vsub v24, v6, v14
    vsd  v24, 48(a1)

    vadd v24, v7, v15
    vsd  v24, 56(a0)
    vsub v24, v7, v15
    vsd  v24, 56(a1)


    # Move to the next group of 8 butterflies.

    addi t2, t2, 8
    j    unroll_loop


    # --------------------------------
    # SCALAR PATH FOR SMALL STAGES
    # len = 2, 4, 8
    # --------------------------------

small_butterfly_loop:

    bge  t2, t3, butterfly_done

    add  a0, t1, t2
    slli a0, a0, 3
    add  a0, s0, a0

    add  a1, t1, t2
    add  a1, a1, t3
    slli a1, a1, 3
    add  a1, s0, a1

    vld  v0, 0(a0)
    vld  v1, 0(a1)
    vld  v5, 0(a6)

    # B * W

    vmul  v2, v1, v5
    vswap v3, v1
    vmul  v4, v3, v5

    vsd  v2, 0(s3)
    vsd  v4, 0(s4)

    flw  ft6, 0(s3)
    flw  ft7, 4(s3)
    fsub.s ft8, ft6, ft7

    flw  ft6, 0(s4)
    flw  ft7, 4(s4)
    fadd.s ft9, ft6, ft7

    fsw  ft8, 0(a7)
    fsw  ft9, 4(a7)

    vld  v1, 0(a7)

    vadd v2, v0, v1
    vsub v3, v0, v1

    vsd  v2, 0(a0)
    vsd  v3, 0(a1)

    # Update W = W * Wlen

    vld  v1, 0(a6)
    vld  v5, 0(s2)

    vmul  v2, v1, v5
    vswap v3, v1
    vmul  v4, v3, v5

    vsd  v2, 0(s3)
    vsd  v4, 0(s4)

    flw  ft6, 0(s3)
    flw  ft7, 4(s3)
    fsub.s ft8, ft6, ft7

    flw  ft6, 0(s4)
    flw  ft7, 4(s4)
    fadd.s ft9, ft6, ft7

    fsw  ft8, 0(a6)
    fsw  ft9, 4(a6)

    addi t2, t2, 1
    j    small_butterfly_loop


    # --------------------------------
    # END OF BUTTERFLY LOOP
    # --------------------------------

butterfly_done:
    add  t1, t1, t0
    j    block_loop


stage_done:
    addi s2, s2, 8
    slli t0, t0, 1
    j    stage_loop


fft_done:
    ebreak