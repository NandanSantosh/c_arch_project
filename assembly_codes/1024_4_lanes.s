# 32-byte scratch for the len-2 lane shuffle: E @0, O @8, S @16, D @24
scratch: .word 0, 0, 0, 0, 0, 0, 0, 0

.text
main:
    la   s0, x
    li   s1, 1024

    # ------------------------------------------------------------
    # Bit-reversal permutation (scalar). One sample = one word.
    # ------------------------------------------------------------
    li   t0, 1
    li   t1, 0
bitrev_i:
    bge  t0, s1, bitrev_done
    li   t2, 512
bitrev_carry:
    bge  t1, t2, bitrev_reduce
    j    bitrev_carry_done
bitrev_reduce:
    sub  t1, t1, t2
    srli t2, t2, 1
    j    bitrev_carry
bitrev_carry_done:
    add  t1, t1, t2
    blt  t0, t1, bitrev_swap
    j    bitrev_next
bitrev_swap:
    slli t3, t0, 2
    add  t3, s0, t3
    slli t4, t1, 2
    add  t4, s0, t4
    lw   t5, 0(t3)
    lw   t6, 0(t4)
    sw   t6, 0(t3)
    sw   t5, 0(t4)
bitrev_next:
    addi t0, t0, 1
    j    bitrev_i

bitrev_done:
    # ------------------------------------------------------------
    # Stage len = 2 (half = 1). Both partners sit in the SAME register
    # (x[2m], x[2m+1]), so regroup through scratch:
    #   E = (x0, x2), O = (x1, x3)  ->  S = E+O = (y0, y2), D = E-O = (y1, y3)
    # W = 1, so no complex multiply is needed.
    # ------------------------------------------------------------
    la   a7, scratch
    li   t1, 0
len2_loop:
    bge  t1, s1, len2_done
    slli a0, t1, 2
    add  a0, s0, a0
    lw   t2, 0(a0)             # x0
    lw   t3, 4(a0)             # x1
    lw   t4, 8(a0)             # x2
    lw   t5, 12(a0)            # x3
    sw   t2, 0(a7)             # E = (x0, x2)
    sw   t4, 4(a7)
    sw   t3, 8(a7)             # O = (x1, x3)
    sw   t5, 12(a7)
    vld    v0, 0(a7)
    vld    v1, 8(a7)
    vadd.h v2, v0, v1          # (x0+x1, x2+x3)
    vsub.h v3, v0, v1          # (x0-x1, x2-x3)
    vsd    v2, 16(a7)
    vsd    v3, 24(a7)
    lw   t2, 16(a7)            # y0
    lw   t3, 20(a7)            # y2
    lw   t4, 24(a7)            # y1
    lw   t5, 28(a7)            # y3
    sw   t2, 0(a0)
    sw   t4, 4(a0)
    sw   t3, 8(a0)
    sw   t5, 12(a0)
    addi t1, t1, 4
    j    len2_loop

len2_done:
    li   t0, 4                 # stage length
    la   s2, tw_table

stage_loop:
    blt  s1, t0, fft_done
    srli t3, t0, 1             # half
    li   t1, 0                 # block start i
    li   t4, 8
    blt  t3, t4, mid_stage     # half = 2 or 4

    # ------------------------------------------------------------
    # half >= 8: 8 butterflies per iteration (4 regs x 2 complex)
    # ------------------------------------------------------------
block_loop8:
    bge  t1, s1, stage_done
    li   t2, 0                 # j
butterfly_loop8:
    bge  t2, t3, butterfly_done8

    add  a0, t1, t2            # a0 = &x[i+j]
    slli a0, a0, 2
    add  a0, s0, a0
    slli a1, t3, 2             # a1 = &x[i+j+half]
    add  a1, a0, a1
    slli a2, t2, 2             # a2 = &W_len[j]
    add  a2, s2, a2

    vld  v0,  0(a0)            # A: (x[j],x[j+1]) ... (x[j+6],x[j+7])
    vld  v1,  8(a0)
    vld  v2, 16(a0)
    vld  v3, 24(a0)
    vld  v4,  0(a1)            # B
    vld  v5,  8(a1)
    vld  v6, 16(a1)
    vld  v7, 24(a1)
    vld  v8,  0(a2)            # W: (W^j, W^j+1) ... (W^j+6, W^j+7)
    vld  v9,  8(a2)
    vld  v10, 16(a2)
    vld  v11, 24(a2)

